const NUM_TABLES = <?php echo (int)$num_tables; ?>;

// Build a fully branded QR card on a single canvas (so download includes branding)
function buildBrandedCard(tableNo, url) {
    const CARD_W = 400;
    const CARD_H = 520;

    const canvas = document.createElement('canvas');
    canvas.width = CARD_W;
    canvas.height = CARD_H;
    const ctx = canvas.getContext('2d');

    // ---- 1. Card background (white with rounded corners look) ----
    ctx.fillStyle = '#ffffff';
    ctx.fillRect(0, 0, CARD_W, CARD_H);

    // Outer gold border
    ctx.strokeStyle = '#FFD700';
    ctx.lineWidth = 6;
    ctx.strokeRect(3, 3, CARD_W - 6, CARD_H - 6);

    // ---- 2. Top dark banner ----
    ctx.fillStyle = '#281C02';
    ctx.fillRect(0, 0, CARD_W, 55);

    ctx.fillStyle = '#FFD700';
    ctx.font = 'bold 20px Arial';
    ctx.textAlign = 'center';
    ctx.textBaseline = 'middle';
    ctx.fillText('QR FOOD HUB', CARD_W / 2, 28);

    // ---- 3. Table number ----
    ctx.fillStyle = '#281C02';
    ctx.font = 'bold 34px Arial';
    ctx.fillText('Table ' + tableNo, CARD_W / 2, 100);

    // ---- 4. Subtitle ----
    ctx.fillStyle = '#888888';
    ctx.font = 'bold 14px Arial';
    ctx.fillText('SCAN TO ORDER', CARD_W / 2, 130);

    // ---- 5. QR code ----
    const qrSize = 260;
    const qrX = (CARD_W - qrSize) / 2;
    const qrY = 165;

    // White padding behind QR (quiet zone)
    ctx.fillStyle = '#ffffff';
    ctx.fillRect(qrX - 10, qrY - 10, qrSize + 20, qrSize + 20);

    // Create QR in an offscreen div, then draw its canvas here
    const temp = document.createElement('div');
    new QRCode(temp, {
        text: url,
        width: qrSize,
        height: qrSize,
        colorDark: '#000000',
        colorLight: '#ffffff',
        correctLevel: QRCode.CorrectLevel.M
    });

    // qrcodejs creates either a <canvas> or an <img>; handle both
    const qrCanvas = temp.querySelector('canvas');
    const qrImg = temp.querySelector('img');

    return new Promise((resolve) => {
        if (qrCanvas) {
            ctx.drawImage(qrCanvas, qrX, qrY, qrSize, qrSize);
            finishDrawing(ctx, CARD_W, CARD_H, tableNo, url);
            resolve(canvas);
        } else if (qrImg) {
            qrImg.onload = () => {
                ctx.drawImage(qrImg, qrX, qrY, qrSize, qrSize);
                finishDrawing(ctx, CARD_W, CARD_H, tableNo, url);
                resolve(canvas);
            };
            qrImg.onerror = () => {
                finishDrawing(ctx, CARD_W, CARD_H, tableNo, url);
                resolve(canvas);
            };
        } else {
            finishDrawing(ctx, CARD_W, CARD_H, tableNo, url);
            resolve(canvas);
        }
    });
}

function finishDrawing(ctx, CARD_W, CARD_H, tableNo, url) {
    // ---- 6. "Point your camera here" ----
    ctx.fillStyle = '#281C02';
    ctx.font = 'bold 16px Arial';
    ctx.textAlign = 'center';
    ctx.fillText('📱 Point your camera here', CARD_W / 2, 460);

    // ---- 7. URL (small, bottom) ----
    ctx.fillStyle = '#999999';
    ctx.font = '10px Arial';
    ctx.fillText('Table ' + tableNo + ' · QR Food Hub', CARD_W / 2, 490);
}

async function generateAll() {
    const baseUrl = document.getElementById('baseUrl').value.replace(/\/+$/, '');
    const grid = document.getElementById('qrGrid');
    grid.innerHTML = '';

    for (let i = 1; i <= NUM_TABLES; i++) {
        const url = `${baseUrl}/index.php?table=${i}`;

        const card = document.createElement('div');
        card.className = 'qr-card';

        // Build the branded canvas
        const brandedCanvas = await buildBrandedCard(i, url);

        // Show it on the page
        brandedCanvas.style.maxWidth = '100%';
        brandedCanvas.style.height = 'auto';
        card.appendChild(brandedCanvas);

        // Download button
        const dl = document.createElement('button');
        dl.className = 'qr-download';
        dl.textContent = '⬇ Download';
        dl.addEventListener('click', () => {
            const a = document.createElement('a');
            a.href = brandedCanvas.toDataURL('image/png');
            a.download = `table-${i}-qr.png`;
            a.click();
        });
        card.appendChild(dl);

        grid.appendChild(card);
    }
}

generateAll();
